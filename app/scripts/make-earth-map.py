#!/usr/bin/env python3
"""
Writes miyatv's world map to src/pages/TV/earth.ts: the land from Natural Earth (public domain, through the world-atlas
TopoJSON), as one SVG path in degrees, x = longitude and y = -latitude. Rounded to the degree, plenty for a map this size.
Run: python3 scripts/make-earth-map.py
"""
import json
import urllib.request
from pathlib import Path

SOURCE = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json"
OUT = Path(__file__).resolve().parent.parent / "src/pages/TV/earth.ts"


def main():
    with urllib.request.urlopen(SOURCE) as res:
        topo = json.load(res)
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]

    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        points = []
        for dx, dy in arc:
            x += dx
            y += dy
            points.append((x * sx + tx, y * sy + ty))
        arcs.append(points)

    def ring(indexes):
        points = []
        for index in indexes:
            part = arcs[index] if index >= 0 else arcs[~index][::-1]
            points.extend(part if not points else part[1:])
        return points

    rings = []
    for geometry in topo["objects"]["land"]["geometries"]:
        polygons = geometry["arcs"] if geometry["type"] == "MultiPolygon" else [geometry["arcs"]]
        rings.extend(ring(r) for polygon in polygons for r in polygon)

    parts = []
    for points in rings:
        rounded = []
        for lon, lat in points:
            point = (round(lon), round(-lat))
            if not rounded or rounded[-1] != point:
                rounded.append(point)
        if len(rounded) < 3:
            continue
        parts.append("M" + "L".join(f"{x} {y}" for x, y in rounded) + "Z")

    OUT.write_text(
        "/** The world's land, from Natural Earth. Generated by scripts/make-earth-map.py. x = longitude, y = -latitude. */\n"
        f"export const LAND_PATH =\n  '{''.join(parts)}'\n"
    )
    print(OUT.name, OUT.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
