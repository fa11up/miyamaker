/** A `#` in the file name wins. Otherwise use the weight the published copy dropped. */
export function fileWeight(relativePath: string): number {
  const file = relativePath.split('/').pop() ?? relativePath
  const stem = file.replace(/\.[^.]+$/, '')
  const hash = stem.lastIndexOf('#')
  if (hash > 0) {
    const weight = Number(stem.slice(hash + 1))
    if (Number.isFinite(weight) && weight >= 0) return weight
  }
  return PUBLISHED_WEIGHTS[relativePath] ?? 1
}
