export function mutatePatch(patch, amount = 0.35) {
  const p = mergePatch(patch)
  const j = (v, span) => v + (Math.random() * 2 - 1) * span * amount
  p.freq = clamp(j(p.freq, p.freq * 0.4), 30, 8000)
  p.fmIndex = clamp(j(p.fmIndex, 1.5), 0, 8)
  p.fold = clamp(j(p.fold, 0.3), 0, 1)
  p.cutoff = clamp(j(p.cutoff, 800), 80, 14000)
  p.filterEnv = clamp(j(p.filterEnv, 12), -12, 60)
  p.pitchEnv = clamp(j(p.pitchEnv, 8), -24, 48)
  p.noise = clamp(j(p.noise, 0.2), 0, 1)
  p.stretch = clamp(j(p.stretch, 0.15), 0, 0.8)
  p.drive = clamp(j(p.drive, 0.4), 0.6, 3)
  p.partials = p.partials.map((v) => clamp(j(v, 0.15), 0, 1))
  p.oscs = p.oscs.map((o) => ({
    ...o,
    ratio: clamp(j(o.ratio, 0.4), 0.25, 8),
    detune: clamp(j(o.detune, 8), -40, 40),
    level: clamp(j(o.level, 0.15), 0, 1),
  }))
  return p
}

function clamp(v, a, b) {
  return Math.max(a, Math.min(b, v))
}
